// (a) Every example and every script the editor generates is valid against docs/alto/alto-script.schema.json
// (JSON Schema draft 2020-12, checked with ajv).

import { test } from 'node:test';
import assert from 'node:assert/strict';
import fs from 'node:fs';
import path from 'node:path';
import Ajv2020 from 'ajv/dist/2020.js';
import { everyBlockScript, examples, outputDir, roundTrip, schemaPath } from './helpers.mjs';
import { EVERYTHING, CASES } from './fixtures/cases.mjs';
import { loadScriptData, parseScriptText } from '../src/lang/index.js';

const schema = JSON.parse(fs.readFileSync(schemaPath, 'utf8'));
const ajv = new Ajv2020({ allErrors: true, strict: false });
const validate = ajv.compile(schema);

function assertSchemaValid(data, what) {
  const ok = validate(data);
  assert.ok(ok, `${what}: ${ajv.errorsText(validate.errors, { separator: '\n' })}`);
}

test('the schema compiles as draft 2020-12', () => {
  assert.equal(schema.$schema, 'https://json-schema.org/draft/2020-12/schema');
  assert.equal(typeof validate, 'function');
});

for (const { file, text } of examples()) {
  test(`schema: example ${file}`, () => assertSchemaValid(JSON.parse(text), file));
  test(`schema: generated round trip of ${file}`, () => {
    const { report } = roundTrip(text);
    assertSchemaValid(JSON.parse(report.pretty), file);
  });
}

test('schema: generated round trip of the EVERYTHING fixture', () => {
  const { report } = roundTrip(EVERYTHING);
  assertSchemaValid(JSON.parse(report.pretty), 'everything');
});

test('schema: generated round trips of every clean validator case', () => {
  for (const c of CASES.filter((x) => x.clean)) {
    const { report } = roundTrip(c.json);
    assertSchemaValid(JSON.parse(report.pretty), c.name);
  }
});

test('schema: files written to test-output', () => {
  if (!fs.existsSync(outputDir)) return;
  for (const f of fs.readdirSync(outputDir).filter((x) => x.endsWith('.alto.json'))) {
    assertSchemaValid(JSON.parse(fs.readFileSync(path.join(outputDir, f), 'utf8')), f);
  }
});

test('schema: a script with every palette block (generated by the editor) is valid and runnable', () => {
  const { data, notes } = everyBlockScript();
  assert.deepEqual(notes, []);
  assertSchemaValid(data, 'every palette block');
  const report = loadScriptData(data);
  assert.ok(report.script, JSON.stringify(report.diagnostics.slice(0, 5)));
  const errors = report.diagnostics.filter((d) => d.severity === 'error');
  assert.deepEqual(errors, []);
  const blockKinds = new Set();
  const walk = (list) => list.forEach((s) => {
    blockKinds.add(s.block);
    for (const k of ['body', 'then', 'else']) if (Array.isArray(s[k])) walk(s[k]);
  });
  walk(data.events[0].body);
  for (const kind of ['goto', 'mine', 'build', 'fill', 'farm', 'craft', 'smelt', 'fetch', 'deposit', 'eat', 'wait', 'message', 'command',
    'send_chat', 'use_item_on_block', 'set_filter', 'place_station', 'pickup_station', 'board_vehicle', 'ride_train', 'leave_vehicle',
    'take_portal', 'stop', 'repeat', 'repeat_until', 'forever', 'if', 'wait_until', 'break', 'call', 'set_var', 'change_var']) {
    assert.ok(blockKinds.has(kind), `${kind} generated`);
  }
  assert.equal(data.events.length, 6);
  fs.mkdirSync(outputDir, { recursive: true });
  fs.writeFileSync(path.join(outputDir, 'generated_every_block.alto.json'), report.pretty);
  // and it reads back the same
  assert.equal(loadScriptData(JSON.parse(report.pretty)).canonical, report.canonical);
  assert.ok(parseScriptText(report.pretty).script);
});
